/**
 * サービス層の入口。**ここには実装を書かない。**
 *
 * 呼ぶ側（`app/api/*` と `pwa/api-shim.ts` と CLI）は
 * これまでどおり `@/lib/service` から import する。中の分け方が変わっても
 * 呼ぶ側を書き換えなくて済むように、入口だけを固定する。
 *
 * ---
 *
 * **なぜ「結果」から切り出さなかったか。**
 *
 * 最初は `result.ts`（結果の保存・CFE更新・波及）を先に出す計画だった。
 * 参照を数えたら、両方向に跨いでいて切れなかった。
 *
 *   結果 → 予定 … `processResult` が `regeneratePlan` を呼ぶ（保存したら作り直す）
 *   予定 → 結果 … FIT取込・セッション実行が `processResult` を呼ぶ
 *
 * これは設計の乱れではなく、このアプリの中心そのもの。
 * 「結果入力 → CFE → 再計算 → 波及 → ルール再検証」が閉じた輪になっている。
 * **輪の途中で切ると、片方向にするために間に合わせの層が要る。**
 * そこまでして分けるものではないので、予定と結果は1つのまとまりに残す。
 *
 * 代わりに、**呼ばれるだけで誰からも参照されない端から**外へ出す。
 * 参照が片方向だと確認できたものだけを動かす（`scripts/ci/check-service-layers.mjs`）。
 *
 * ---
 *
 * 分け方の方針:
 *
 *   index.ts     入口。再exportだけ
 *   run.ts       M-4 セッション中の入力。`workflow` を呼ぶだけ
 *   workflow.ts  予定と結果の輪。ここから順に端を剥がしていく
 *
 * **移動のときは中身を変えない。** ロジックの変更と場所の変更を同時にやると、
 * 落ちたときにどちらが原因か切り分けられなくなる。
 */
export * from "./workflow";
export * from "./run";
